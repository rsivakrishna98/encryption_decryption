# Clear Key CENC – Practical Encryption Flow

## 1. Input Values

In our Clear Key CENC project, Python generates only two values:

```text
Algorithm: AES-128-CTR

KID:
00112233445566778899aabbccddeeff

KEY:
5f1ef79b5aae392653793bdd5ad2dd53
```

Note: These are illustrative example values.

| Parameter | Generated by | Purpose |
|---|---|---|
| KID | Python | Identifies the encryption key |
| KEY | Python | Encrypts and decrypts video samples |
| IV | Shaka Packager | Provides the starting counter value for AES-CTR |

## 2. Original Video Sample

Shaka Packager reads the video samples from the original MP4 file.

For example, assume one protected sample contains these 16 bytes:

```text
Original sample (M0):

000000206674797069736f6d00000200
```

This is an illustrative sample, not necessarily the actual first 16 bytes of the MP4.

## 3. IV / Counter Generation

We do not generate the IV in our Python key-generation script.

Shaka Packager handles the IV/counter process during CENC encryption.

For illustration, assume the counter block is:

```text
IV / Counter:

a3e38b586253c3d61a6ecfa88f925fa1
```

The actual IV must be obtained from the encrypted MP4 metadata or the packager configuration. This example counter is not claimed to be the actual generated IV.

## 4. AES-CTR Keystream Generation

AES-CTR encrypts the counter block using the secret KEY.

```text
KEY:
5f1ef79b5aae392653793bdd5ad2dd53

IV / Counter:
a3e38b586253c3d61a6ecfa88f925fa1

AES-128 encryption of counter using KEY:

Keystream:
(16 bytes generated by AES)
```

The AES encryption output is called the keystream.

## 5. XOR Operation

The original sample is XORed with the generated keystream.

```text
Original sample:
000000206674797069736f6d00000200

Keystream:
(16 bytes generated by AES)

XOR operation:
Original sample XOR Keystream

Encrypted sample:
(16 bytes of encrypted output)
```

This is how AES-CTR encrypts the sample data.

## 6. CENC Metadata Added to MP4

Shaka Packager also writes encryption metadata into the MP4 container.

| MP4 Box | Purpose |
|---|---|
| encv | Indicates encrypted video |
| sinf | Contains protection information |
| frma | Identifies the original video format |
| schm | Identifies the encryption scheme (cenc) |
| schi | Contains scheme-specific information |
| tenc | Contains default encryption parameters and KID |
| pssh | Contains protection-system information |
| senc | Contains sample encryption information |
| saiz | Contains auxiliary information sizes |
| saio | Contains auxiliary information offsets |

## 7. Final Encrypted MP4

```text
Original MP4
     |
     v
Shaka Packager reads video samples
     |
     v
AES-CTR encryption using KEY and IV/counter
     |
     v
XOR original sample with generated keystream
     |
     v
Add CENC encryption metadata
     |
     v
sample_encrypted.mp4
```

## 8. Decryption Process

During decryption, the reverse process happens.

```text
Encrypted MP4
     |
     v
Read KID from MP4 metadata
     |
     v
Find the matching KEY
     |
     v
Use the same IV/counter information
     |
     v
Generate the same AES-CTR keystream
     |
     v
XOR encrypted sample with keystream
     |
     v
Recover original video sample
     |
     v
Decrypted MP4
```

## 9. Python Key Generation

Our script generates only KID and KEY:

```python
import secrets
import json
from pathlib import Path

KEY_FILE = Path("keys/clear_key.json")

kid = secrets.token_bytes(16)
key = secrets.token_bytes(16)

KEY_FILE.parent.mkdir(parents=True, exist_ok=True)

data = {
    "kid": kid.hex(),
    "key": key.hex()
}

KEY_FILE.write_text(json.dumps(data, indent=4))
KEY_FILE.chmod(0o600)

print("Clear Key generated successfully!")
print("KID:", kid.hex())
print("KEY:", key.hex())
```

## 10. Shaka Packager Encryption Command

```bash
packager \
  "in=input/sample.mp4,stream=video,output=output/encrypted/sample_encrypted.mp4" \
  --enable_raw_key_encryption \
  --keys label=:key_id=KID_VALUE:key=KEY_VALUE \
  --protection_scheme cenc \
  --clear_lead 0
```

Replace KID_VALUE and KEY_VALUE with the generated values from clear_key.json.

## 11. Important Difference: AES-CBC vs Clear Key CENC

| Feature | AES-CBC | Clear Key CENC |
|---|---|---|
| Algorithm | AES-128 | AES-128 |
| Mode | CBC | CTR (cenc) |
| Encryption target | Complete file | Protected media samples |
| KEY generation | Python | Python |
| IV handling | Python generates IV | Packager handles IV/counter |
| KID | Not required | Required |
| XOR | Original block XOR IV/previous ciphertext | Original sample XOR AES-generated keystream |
| Metadata | Not required | CENC metadata added |
| Output | Encrypted binary file | Encrypted MP4 |

**Remember:**

- KID = Key Identifier.
- KEY = Secret encryption key.
- IV = Initialization Vector.
- AES-CTR = Generates a keystream by encrypting counter blocks.
- XOR = Combines original sample data with the keystream.
- CENC = Defines how encrypted media samples and their encryption information are represented in the MP4 container.

**Important:** Clear Key CENC is not the same as commercial DRM. Protect the content KEY and never commit it to a public GitHub repository.

The sample keystream and encrypted output have intentionally not been filled with invented hexadecimal values. They must be calculated using the exact counter convention and sample-encryption configuration to be accurate.